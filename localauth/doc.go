// Package localauth 是本地密码登录的共享守卫 —— 把「一次登录尝试里，
// 除了『这个密码对不对』之外的所有事」封起来：限流、退避、时序一致、
// 注册准入、密码哈希策略。
//
// # 它【故意】不做的事
//
// 本包不知道任何消费者的存在: 不碰数据库、不认识用户表、不签任何 token、
// 不发邮件、不知道「角色」是什么。它只回答一个问题: 这次尝试放不放行。
//
//	本包负责     →  守卫判定 + 时序一致 + 密码哈希策略
//	调用方负责   →  用户从哪来、放行之后签什么、失败之后给用户看什么
//
// 边界画在这里, 是因为前者对任何应用都一样, 后者对任何应用都不一样。
//
// # 为什么一开始就写成「外部包」
//
// 下游不止一个。本包因此从第一天起就不引用任何应用内部类型 ——
// 剥离成独立仓时改 import 路径即可, 不需要重写。
// 这与 pkg/gormdb 的来历相反: 那个是复制三次之后才上提的。
//
// # 两条铁律
//
//  1. 本包【永不】import 宿主仓的 internal/ —— 依赖方向单向。
//  2. 应用特有值【不进】本包: 数据库、邮件通道、准入策略、限流存储,
//     全部由消费者经构造参数注入。这里出现任何一个具体应用的字符串,
//     就是抽象泄漏的开始。
//
// # 安全上不可动摇的六条
//
//  1. bcrypt 只有【一个】调用点, 且它支配所有与凭据相关的返回路径。
//     绕过它的任何早退 (例如「用户不存在就直接 return」) 都是时序预言机。
//  2. 该调用点的错误在原地坍缩为 bool —— 错误值不得逃出去。
//     否则「用户存在但没有密码」会因错误类型不同而走到另一个分支,
//     泄漏变成状态码级的, 一次请求即可读出。
//  3. 用户不存在时也要跑等量的工作 (dummy hash), 且 dummy 必须是【合法的】
//     bcrypt hash —— 非法 hash 会在 20ns 内返回, 满足 1 和 2 仍然泄漏。
//  4. 凡与凭据相关的失败, 对外是同一个错误码。LoginOutcome 因此不携带失败原因:
//     这条由结构保证, 不靠调用方自觉。
//  5. 计数必须对【不存在的用户名】同样记录 —— 否则计数器自己就是枚举预言机。
//     这也决定了键是提交上来的字符串而不是解析后的用户 id。
//  6. 两个维度的计数必须是【两个独立的计数器】, 不得合成一个复合键:
//     复合键被两个维度的轮换分别绕开, 严格弱于任一单键。
